import pytest

from app.services.languages import source_language


@pytest.mark.parametrize(
    ("path", "content", "expected"),
    [
        ("app.ts", b"const answer = 42", "TypeScript"),
        ("app.tsx", b"export const App = () => <p>Hello</p>", "TypeScript"),
        ("view.tsx", b"<TSProvider />;", "TypeScript"),
        ("app.jsx", b"export const App = () => <p>Hello</p>", "JavaScript"),
        ("app.mjs", b"export const answer = 42", "JavaScript"),
        ("app.py", b"print('hello')", "Python"),
        ("index.html", b"<!doctype html><p>Hello</p>", "HTML"),
        ("style.css", b"p { color: red; }", "CSS"),
        ("bin/tool", b"#!/usr/bin/env -S python3 -u\nprint('hello')", "Python"),
        ("README.md", b"# Hello", None),
        ("AGENTS.md", b"# Development guidelines", None),
        ("machine.md", b'(define_insn "add" [])', "GCC Machine Description"),
        ("translations.ts", b'<?xml version="1.0"?><TS />', None),
        ("package.json", b'{"name":"hello"}', None),
        ("config.yaml", b"name: hello", None),
        ("pyproject.toml", b"[project]\nname='hello'", None),
        ("uv.lock", b"version = 1", None),
        ("bun.lock", b'{"lockfileVersion":1}', None),
        ("mix.lock", b'%{"dependency" => {:hex, :dependency}}', None),
        ("docs/example.py", b"print('example')", None),
        ("vendor/module.py", b"print('vendor')", None),
        ("node_modules/package/index.js", b"const answer = 42", None),
        ("dist/app.js", b"const answer = 42", None),
        ("app.min.js", b"const answer=42", None),
        ("api.pb.go", b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api", None),
        ("api.py", b"# Generated by the protocol buffer compiler. DO NOT EDIT!\n", None),
        ("source.py", b"message = 'do not edit this text'", "Python"),
        ("image.py", b"image\0data", None),
        ("unknown.txt", b"hello", None),
    ],
)
def test_source_language(path: str, content: bytes, expected: str | None) -> None:
    assert source_language(path, content) == expected
